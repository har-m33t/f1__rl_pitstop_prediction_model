import pandas as pd
import numpy as np

def create_target_variable(df: pd.DataFrame) -> pd.DataFrame:
    """
    Creates the target variable for pit stop prediction.
    If 'PitInTime' is not null, the driver made a pit stop at the end of the lap.
    """
    if "PitInTime" in df.columns:
        df["PitStopObserved"] = df["PitInTime"].notnull().astype(int)
    return df

def create_lag_features(df: pd.DataFrame) -> pd.DataFrame:
    """
    Creates lag features such as previous lap time to capture tire degradation and pace drop-off.
    Must be grouped by DriverNumber and Race/Year to avoid lagging across races or drivers.
    """
    # Assuming 'Track' and 'Year' represent a unique event 
    # (If we only have one race now, DriverNumber is enough, but adding Track/Year is robust)
    group_cols = ["Year", "Track", "DriverNumber"] if "Track" in df.columns and "Year" in df.columns else ["DriverNumber"]
    
    df = df.sort_values(by=group_cols + ["LapNumber"]).reset_index(drop=True)
    
    if "LapTime" in df.columns:
        df["PrevLapTime"] = df.groupby(group_cols)["LapTime"].shift(1)
        # Lap time difference (degradation proxy)
        df["LapTimeDiff"] = df["LapTime"] - df["PrevLapTime"]
        
    return df

def create_advanced_features(df: pd.DataFrame) -> pd.DataFrame:
    """
    Creates advanced RL features such as Tire Age, Degradation Slope, and Track Status proxies.
    """
    group_cols = ["Year", "Track", "DriverNumber"] if "Track" in df.columns and "Year" in df.columns else ["DriverNumber"]
    
    # Ensure 'Stint' is used if it exists for stint grouping
    stint_group_cols = group_cols + (["Stint"] if "Stint" in df.columns else [])
    
    # Ensure sorted order for rolling calculations
    df = df.sort_values(by=group_cols + ["LapNumber"]).reset_index(drop=True)
    
    # 1. Tire Age
    if "TyreLife" in df.columns:
        df["TireAge"] = df["TyreLife"].ffill().fillna(0)
    else:
        # Fallback approximation: Just count laps in the current stint
        df["TireAge"] = df.groupby(stint_group_cols).cumcount() + 1
            
    # 2. Lap time delta vs fresh tire
    # We find the best (minimum) lap in the stint as a proxy for fresh tire pace and compare 
    if "LapTime" in df.columns:
        df["StintBestLap"] = df.groupby(stint_group_cols)["LapTime"].transform("min")
        df["LapTimeDeltaFresh"] = df["LapTime"] - df["StintBestLap"]
        df = df.drop(columns=["StintBestLap"])
        
    # 3. Degradation slope (rolling window)
    if "LapTimeDiff" in df.columns: # Requires create_lag_features to have run
        # Rolling average of pace difference over last 3 laps across the stint
        df["DegradationSlope"] = df.groupby(stint_group_cols)["LapTimeDiff"].transform(
            lambda x: x.rolling(window=3, min_periods=1).mean()
        )
        df["DegradationSlope"] = df["DegradationSlope"].fillna(0)
        
    # 4. Track temperature proxy
    # 'TrackTemp' comes from weather data. Handle NAs so it's clean for RL.
    if "TrackTemp" in df.columns:
        df["TrackTemp"] = df["TrackTemp"].ffill().bfill()
        
    # 5. Safety car indicator (binary)
    # FastF1 TrackStatus: '1': clear, '4': SC, '6': VSC
    if "TrackStatus" in df.columns:
        # Some rows might have multiple status flags, e.g. "14", check if "4" or "6" is in string
        df["IsSafetyCar"] = df["TrackStatus"].astype(str).str.contains("4|6").astype(int)
        
    return df

def scale_and_encode_features(df: pd.DataFrame) -> pd.DataFrame:
    """
    One-hot encodes categorical variables and boolean flags.
    """
    # Convert booleans to int
    bool_cols = ["IsPersonalBest", "FreshTyre"]
    for col in bool_cols:
        if col in df.columns:
            df[col] = df[col].astype(float).fillna(0).astype(int)
            
    # Categorical encoding
    if "Compound" in df.columns:
        df = pd.get_dummies(df, columns=["Compound"], dummy_na=True, prefix="Compound")
    
    # We could also encode Track, but that could result in too many columns for RL. 
    # Leaving it to the model wrapper for now.

    return df

def feature_engineering(df: pd.DataFrame) -> pd.DataFrame:
    """
    Master function to apply all feature engineering steps.
    """
    df = create_target_variable(df)
    df = create_lag_features(df)
    df = create_advanced_features(df)
    df = scale_and_encode_features(df)
    
    # Fill NAs generated by lagging
    if "PrevLapTime" in df.columns:
        df["PrevLapTime"] = df.groupby("DriverNumber")["PrevLapTime"].bfill()
        if "LapTimeDiff" in df.columns:
            df["LapTimeDiff"] = df["LapTimeDiff"].fillna(0)
        
    return df

